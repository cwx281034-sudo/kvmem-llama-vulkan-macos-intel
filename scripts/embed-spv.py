#!/usr/bin/env python3
"""Embed the compiled KVMem stage-in SPIR-V as a C++ translation unit.

CMake runs glslc on src/adapter/vulkan-shaders/*.comp and then this script, so
the SPIR-V lands in the binary without a runtime compiler. The stage-in engine
looks a pipeline up by the PIPE_* enum in llama-kvmem-stagein-vulkan.cpp; the
order here must match that enum.

Usage: embed-spv.py <out.cpp> <name=spv> [<name=spv> ...]
"""

import sys


def main() -> int:
    if len(sys.argv) < 3:
        sys.stderr.write("usage: embed-spv.py <out.cpp> <name=spv>...\n")
        return 2

    out = sys.argv[1]
    units = []
    for arg in sys.argv[2:]:
        name, _, path = arg.partition("=")
        if not name or not path:
            sys.stderr.write(f"bad argument {arg!r}, expected name=path\n")
            return 2
        with open(path, "rb") as fh:
            data = fh.read()
        if len(data) % 4 or not data:
            sys.stderr.write(f"{path}: not a non-empty SPIR-V word stream\n")
            return 1
        units.append((name, data))

    with open(out, "w", encoding="utf-8") as fh:
        fh.write("// Generated by scripts/embed-spv.py. Do not edit.\n")
        fh.write("//\n")
        fh.write("// SPIR-V for the KVMem stage-in compute pipelines, compiled from\n")
        fh.write("// src/adapter/vulkan-shaders/*.comp by glslc at build time.\n")
        fh.write("\n")
        fh.write('#include <cstddef>\n')
        fh.write('#include <cstdint>\n')
        fh.write("\n")
        fh.write("namespace {\n\n")

        for name, data in units:
            fh.write(f"// {name}: {len(data) // 4} words\n")
            fh.write(f"const uint32_t spv_{name}[] = {{\n")
            for off in range(0, len(data), 16):
                # A SPIR-V file is a little endian stream of 32 bit words, and pCode points at
                # those words. A 0xAABBCCDDu literal stores its bytes little
                # endian in memory, so each word has to be emitted with its
                # bytes reversed relative to the file: the file holds 03 02 23
                # 07 for the magic number 0x07230203.
                words = [
                    f"0x{int.from_bytes(data[i:i + 4], 'little'):08x}u"
                    for i in range(off, min(off + 16, len(data)), 4)
                ]
                fh.write("    " + ", ".join(words) + ",\n")
            fh.write("};\n\n")

        fh.write("struct Unit {\n"
                 "    const char *    name;\n"
                 "    const uint32_t *data;\n"
                 "    uint32_t        words;\n"
                 "};\n\n")
        fh.write("const Unit units[] = {\n")
        for name, data in units:
            fh.write(f'    {{ "{name}", spv_{name}, {len(data) // 4} }},\n')
        fh.write("};\n\n")
        fh.write("}  // namespace\n\n")
        fh.write("// Lookup mirrors the PIPE_* enum in llama-kvmem-stagein-vulkan.cpp.\n")
        fh.write("uint32_t kvmem_vk_spv_words(int pipe) {\n"
                 "    if (pipe < 0 || (size_t) pipe >= sizeof(units) / sizeof(units[0])) {\n"
                 "        return 0;\n"
                 "    }\n"
                 "    return units[pipe].words;\n"
                 "}\n\n")
        fh.write("const uint32_t * kvmem_vk_spv_data(int pipe) {\n"
                 "    if (pipe < 0 || (size_t) pipe >= sizeof(units) / sizeof(units[0])) {\n"
                 "        return nullptr;\n"
                 "    }\n"
                 "    return units[pipe].data;\n"
                 "}\n")

    return 0


if __name__ == "__main__":
    sys.exit(main())